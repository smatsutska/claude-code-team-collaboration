#!/usr/bin/env python3
"""gen_metrics.py - reconciles estimated vs measured effort, wave by wave, and generates
metrics/dashboard.md.

Input:  metrics/w*-actuals.md  (one file per wave; hand-filled where not derivable from git)
Output: metrics/dashboard.md   (generated - "one fact, one home": never hand-written)

Each actuals file is a list of `- key_wN: value  # comment` lines. Keys ending in the wave suffix are
grouped by wave; a key with an empty value is reported as "not collected yet" rather than dropped,
so a missing measurement stays visible.

PUBLIC VERSION NOTE
-------------------
In the working repository this script reads absolute person-day figures. Here, effort is **indexed
to the traditional baseline estimate = 100**, because absolute effort figures are commercial. Every
ratio the proof of concept argues from survives the indexing; nothing else does, which is the point.

Usage: python scripts/gen_metrics.py
"""
import glob
import os
import re

OUT = "metrics/dashboard.md"

# Ordered labels for the process section. Keys are given without the wave suffix.
LABELS = [
    ("status", "Status"),
    ("questions_to_architect", "Questions to the architect"),
    ("lead_time_gate_to_pr_hours", "Calendar hours, readiness gate to first PR"),
    ("architect_lines_on_branch", "Lines on the trial branch written by the architect"),
    ("review_defects_structural", "Structural defects found in review"),
    ("review_defects_behaviour", "Behaviour defects found in review"),
    ("coherence_findings_true", "Coherence findings confirmed true by a non-builder"),
    ("merges_native_review", "Merges with a native platform review"),
    ("merges_second_person_before_merge", "Merges with a second-person review before merge"),
    ("merges_declared_waiver", "Merges under a declared waiver"),
    ("merges_no_review_no_waiver", "Merges with no review and no declared waiver"),
    ("pr_share_pct", "Share of work that went through a PR (%)"),
    ("direct_commits_main_peak", "Direct commits to `main` in one five-day stretch"),
    ("ac_added_without_cr", "Acceptance criteria added to approved specs without a change request"),
    ("reconcile_invoked", "`/reconcile` invocations (code written without a spec)"),
    ("contradictions_resolved_pre_merge", "Coherence contradictions resolved at root, before merge"),
    ("method_share_pct", "Share of changed lines spent on the method itself (%)"),
    ("review_defects_gates_green", "Defects found by human review with every gate green"),
    ("change_requests", "Change requests registered"),
    ("first_pass", "First-pass acceptance (FRs passed first time / FRs verified)"),
    ("rows_rejected_pct", "Initial data migration: rows rejected, each with a traced reason"),
]
EFFORT_KEYS = ("build_baseline_index", "build_cc_estimate_index", "build_actual_index")
COMBINED = ("pr_spec_first", "pr_total", "ci_runs", "ci_red",
            "contradictions_scope_creep", "contradictions_spec_drift",
            "contradictions_test_gap", "orphan_fr")


def load(path):
    """Returns {wave: {key_without_suffix: value}} for one actuals file."""
    waves: dict[str, dict[str, str]] = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^\s*-\s*([a-z0-9_]+?)_(w\d+):\s*(.*)$", line)
        if m:
            waves.setdefault(m.group(2), {})[m.group(1)] = m.group(3).split("#")[0].strip()
    return waves


def num(value):
    try:
        return float(value.replace(",", "."))
    except (AttributeError, ValueError):
        return None


data: dict[str, dict[str, str]] = {}
for path in sorted(glob.glob(os.path.join("metrics", "w*-actuals.md"))):
    for wave, values in load(path).items():
        data.setdefault(wave, {}).update(values)
waves = sorted(data, key=lambda w: int(w[1:]))


def pct(a, b):
    return f"{(a - b) / a * 100:.0f}%" if a and b is not None else "n/a"


out = [
    "# Metrics (GENERATED)",
    "",
    "> Generated by `scripts/gen_metrics.py` from `metrics/w*-actuals.md` - do not edit by hand.",
    "> The **curve over time** (wave after wave) is the evidence, not any single number.",
    "",
    "## Effort: estimated vs measured (build only)",
    "",
    "Indexed to the traditional baseline estimate = 100. Absolute person-days are commercial and",
    "are not published; every ratio below is unaffected by the indexing.",
    "",
    "| | " + " | ".join(w.upper() for w in waves) + " |",
    "|---|" + "---:|" * len(waves),
]
rows = [
    ("Traditional baseline (no Claude Code)", "build_baseline_index"),
    ("Plan with Claude Code", "build_cc_estimate_index"),
    ("**Actual (declared)**", "build_actual_index"),
]
for label, key in rows:
    out.append(f"| {label} | " + " | ".join(data[w].get(key, "-") or "-" for w in waves) + " |")
out.append("| **Uplift vs baseline** | " + " | ".join(
    pct(num(data[w].get("build_baseline_index")), num(data[w].get("build_actual_index"))) for w in waves) + " |")
out.append("| Under our own AI-assisted plan by | " + " | ".join(
    pct(num(data[w].get("build_cc_estimate_index")), num(data[w].get("build_actual_index"))) for w in waves) + " |")
out += [
    "",
    "> **Read these caveats before quoting any number:**",
    "> - In waves 0 and 1 every governed line was built **by the architect who designed the method**,",
    ">   not by the team the operating model is written for. Trial 3 (wave 2) is the first exception.",
    "> - **Build only.** The functional team's effort is not measured, so the build uplift is a",
    ">   **ceiling**, not a result. Bet #22 tests the full cost.",
    "> - Wave 0 is structurally anomalous (one-off investment in the gates).",
    "> - Effort is **declared**, not tracked, and is human supervision effort measured against a",
    ">   traditional build estimate. Always state this clause.",
    "",
]

for w in waves:
    d = data[w]
    out += [f"## {w.upper()} - process and gates", ""]
    if d.get("pr_spec_first"):
        out.append(f"- Spec-first PRs: {d['pr_spec_first']} / {d.get('pr_total', '-')}")
    if d.get("contradictions_spec_drift"):
        out.append(
            "- Coherence gate contradictions - scope creep: {} · spec-drift: {} · test gap: {} · orphan FR: {}".format(
                d.get("contradictions_scope_creep", "-"), d.get("contradictions_spec_drift", "-"),
                d.get("contradictions_test_gap", "-"), d.get("orphan_fr", "-")))
    if d.get("ci_runs"):
        out.append(f"- CI runs red: {d.get('ci_red', '-')} / {d['ci_runs']} (waves 0-1 cumulative)")
    for key, label in LABELS:
        if d.get(key):
            out.append(f"- {label}: {d[key]}")
    known = {k for k, _ in LABELS} | set(EFFORT_KEYS) | set(COMBINED)
    for key, value in d.items():
        if key not in known and value:
            out.append(f"- {key}: {value}")
    missing = [k for k, v in d.items() if not v]
    if missing:
        out.append("- **Not collected yet:** " + ", ".join(f"`{k}`" for k in missing))
    out.append("")

open(OUT, "w", encoding="utf-8").write("\n".join(out))
print(f"wrote {OUT}")
