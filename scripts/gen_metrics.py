#!/usr/bin/env python3
"""gen_metrics.py - reconciles estimated vs measured effort and generates metrics/dashboard.md.

Input:  metrics/w0-actuals.md  (actuals; hand-filled where not derivable from git)
Output: metrics/dashboard.md   (generated - "one fact, one home": never hand-written)

PUBLIC VERSION NOTE
-------------------
In the working repository this script reads absolute person-day figures. Here, effort is **indexed
to the traditional baseline estimate = 100**, because absolute effort figures are commercial. Every
ratio the proof of concept argues from survives the indexing; nothing else does, which is the point.

Usage: python scripts/gen_metrics.py
"""
import os
import re

SRC = os.environ.get("ACTUALS", "metrics/w0-actuals.md")
OUT = "metrics/dashboard.md"


def load(p):
    d = {}
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            m = re.match(r"^\s*-\s*([a-z0-9_]+):\s*(.*)$", line)
            if m:
                d[m.group(1)] = m.group(2).split("#")[0].strip()
    return d


def num(d, k):
    try:
        return float(d.get(k, "").replace(",", "."))
    except ValueError:
        return None


d = load(SRC)
baseline = num(d, "build_baseline_index_w0")
cc = num(d, "build_cc_estimate_index_w0")
actual = num(d, "build_actual_index_w0")

uplift_base = f"{(baseline - actual) / baseline * 100:.0f}%" if baseline and actual is not None else "n/a"
delta_cc = f"{(cc - actual) / cc * 100:.0f}%" if cc and actual is not None else "n/a"


def g(k):
    return d.get(k, "-")


out = [
    "# Metrics - wave 0 (GENERATED)",
    "",
    "> Generated by `scripts/gen_metrics.py` from `metrics/w0-actuals.md` - do not edit by hand.",
    "> The **curve over time** (wave after wave) is the evidence, not any single number.",
    "",
    "## Effort: estimated vs measured",
    "",
    "Indexed to the traditional baseline estimate = 100. Absolute person-days are commercial and",
    "are not published; every ratio below is unaffected by the indexing.",
    "",
    "| | Index |",
    "|---|---:|",
    f"| Traditional baseline (no Claude Code) | {g('build_baseline_index_w0')} |",
    f"| Estimate with Claude Code (planned) | {g('build_cc_estimate_index_w0')} |",
    f"| **Actual, wave 0** | **{g('build_actual_index_w0')}** |",
    "",
    f"- **Uplift vs baseline:** {uplift_base}",
    f"- **Came in under our own Claude-Code-assisted estimate by:** {delta_cc}",
    "",
    "> **Read these caveats before quoting the number:**",
    "> - Wave 0 was executed **by the harness designers**, not by the seven-person team the operating",
    ">   model is written for. It proves the harness works for its authors - a much weaker claim.",
    "> - Wave 0 is **structurally anomalous**: most of its cost was one-off investment in the harness",
    ">   (five gates, scripts, retrospective). Later waves will differ, on a larger base.",
    "> - This is human **supervision** effort measured against a traditional **build** estimate. The",
    ">   right measure for the commercial question, but not like-for-like. Always state this clause.",
    "",
    "## Spec-driven process",
    "",
    f"- **spec-first** PRs: {g('pr_spec_first_w0')} / {g('pr_total_w0')}",
    f"- `/reconcile` invocations (code written without a spec): {g('reconcile_invoked_w0')}",
    "",
    "## Coherence gate contradictions, by kind",
    "",
    f"- scope creep: {g('contradictions_scope_creep_w0')} · spec-drift: {g('contradictions_spec_drift_w0')} · "
    f"test gap: {g('contradictions_test_gap_w0')} · orphan FR: {g('orphan_fr_w0')}",
    f"- resolved **at root, before merge**: {g('contradictions_resolved_pre_merge_w0')}",
    "",
    "## Delivery (initial data migration)",
    "",
    f"- first official version loaded · **{g('rows_rejected_pct_w0')} of rows rejected**, each with a traced reason",
    "",
]
missing = [k for k in ("build_actual_index_w0", "pr_spec_first_w0") if not d.get(k)]
if missing:
    out += ["## To be filled in", "", "Missing actuals: " + ", ".join(missing) + " (see `metrics/w0-actuals.md`).", ""]

open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {OUT}")
